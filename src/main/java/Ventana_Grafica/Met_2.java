    private void calc_2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calc_2ActionPerformed
        try {
            // 1. Obtener el valor de 'n' del JTextField
            // Supongamos que tu JTextField se llama txtValorGauss
            long n = Long.parseLong(text_2.getText());

            // Método de Gauss
            long inicioGauss = System.nanoTime();
            long sumaGauss = (n * (n + 1)) / 2;
            long finGauss = System.nanoTime();
            double tiempoGauss = (finGauss - inicioGauss) / 1_000_000_000.0;

            // 2. Mostrar los resultados en los Labels (asumiendo que creaste los Labels)
            resp_2_1.setText("Iteraciones: 0 (Cálculo directo)");
            resp_2_2.setText("Suma total: " + sumaGauss);
            resp_2_3.setText(String.format("Tiempo: %.8f seg", tiempoGauss));

        } catch (NumberFormatException e) {
            // Manejar el error si no es un número válido
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese un número entero válido.");
        }
    }//GEN-LAST:event_calc_2ActionPerformed

