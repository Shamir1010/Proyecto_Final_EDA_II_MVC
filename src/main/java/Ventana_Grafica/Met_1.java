    private void calc_1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calc_1ActionPerformed
        try {
            // 1. Obtener el tamaño del arreglo desde la caja de texto
            int cantidad = Integer.parseInt(text_1.getText());

            // 2. Crear el arreglo y llenarlo automáticamente con valores aleatorios
            double[] arreglo = new double[cantidad];
            java.util.Random random = new java.util.Random();

            for (int i = 0; i < cantidad; i++) {
                // Genera números aleatorios entre 1.0 y 100.0 con 2 decimales
                arreglo[i] = Math.round((1 + (99 * random.nextDouble())) * 100.0) / 100.0;
            }

            // 3. Inicializar variables
            double sumaTotal = 0.0;
            int iteraciones = 0;

            // 4. Iniciar el temporizador
            long inicio = System.nanoTime();

            // 5. Recorrer el arreglo para sumar los valores
            for (double valor : arreglo) {
                sumaTotal += valor;
                iteraciones++;
            }

            // 6. Detener el temporizador
            long fin = System.nanoTime();
            double tiempoEjecucion = (fin - inicio) / 1_000_000_000.0;

            // 7. Mostrar los resultados en los espacios correspondientes
            // (Asegúrate de que los nombres de los Labels coincidan con los de tu diseño)
            resp_1_1.setText(String.valueOf(iteraciones));

            // Usamos String.format para mostrar correctamente los decimales y evitar que parezca tiempo
            resp_1_2.setText(String.format("%.2f", sumaTotal));
            resp_1_3.setText(String.format("%.8f", tiempoEjecucion));

        } catch (NumberFormatException e) {
            // Si el usuario escribe letras o deja en blanco, muestra un error
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese un número entero válido.");
        }
    }//GEN-LAST:event_calc_1ActionPerformed

